-- Расписание: 36 отправлений на маршрут (3 суток по 12 рейсов, с 06:00, каждые 90 минут).
-- Рекурсивный CTE — генерация расписания средствами MySQL 8.
-- Распределение автобусов по рейсам в сиде упрощённое (без проверки занятости):
-- в проде занятость контролируется приложением/триггером.
INSERT INTO trips (route_id, bus_id, departure_at)
WITH RECURSIVE seq(n) AS (
    SELECT 0
    UNION ALL
    SELECT n + 1 FROM seq WHERE n < 35      -- 0..35: 3 дня × 12 рейсов
)
SELECT
    r.id,
    1 + ((r.id + s.n) MOD 20),
    TIMESTAMP(DATE_ADD(CURDATE(), INTERVAL s.n DIV 12 DAY), '06:00:00')
        + INTERVAL (s.n MOD 12) * 90 MINUTE
FROM routes r
CROSS JOIN seq s;
